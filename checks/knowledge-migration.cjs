const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
let saved=null;
const previous={expenses:[{id:'USER-EXPENSE',amount:123.45,note:'用户原有报销'}],receipts:[{id:'USER-RECEIPT'}],draft:{values:{title:'用户草稿'}},docs:[{id:'policy-travel',content:'旧的空泛制度'},{id:'user-upload',title:'我的制度',content:'用户上传资料'}],logs:[{id:'old-user-chat',question:'深圳住宿多少钱',answer:'保留当时原始回答',source:'原答复',sample:false},{id:'QA1000',question:'发票抬头和税号是什么',answer:'旧的空泛答复',source:'示例',sample:true}]};
const context=vm.createContext({console,crypto:require('node:crypto').webcrypto,localStorage:{getItem:()=>JSON.stringify(previous),setItem:(key,value)=>{saved=JSON.parse(value);}},document:{addEventListener(){},getElementById(){return{addEventListener(){}};}},Blob,URL,setTimeout,clearTimeout});
for(const name of ['knowledge-data.js','knowledge-engine.js','app.js'])vm.runInContext(fs.readFileSync('dist/'+name,'utf8').replace(/shell\(\);render\(\);\s*$/,''),context);
assert.ok(saved,'old data is migrated and saved');
assert.deepEqual(saved.expenses,previous.expenses);
assert.deepEqual(saved.receipts,previous.receipts);
assert.deepEqual(saved.draft,previous.draft);
assert.equal(saved.docs.length,9);
assert.equal(saved.docs.find(d=>d.id==='user-upload').content,'用户上传资料');
assert.ok(!saved.docs.some(d=>d.id==='policy-travel'));
assert.equal(saved.docs.filter(d=>d.builtin).length,8);
assert.equal(saved.logs[0].answer,'保留当时原始回答');
assert.match(saved.logs[1].answer,/DEMO-TAX-20261001/);
assert.equal(saved.knowledgeVersion,'2026.10-v2');
saved=null;
vm.runInContext('migrateKnowledge()',context);
assert.equal(saved,null,'migration is idempotent');
console.log('PASS: migration preserves expenses, receipts, draft, uploads and user history; seeded knowledge upgrades exactly once.');
